assert.equal(sample.form.elements.inquiry_type.value,'Sample availability question');
sample.form.elements.inquiry_type.value='Product document request';
sample.form.listeners.submit({preventDefault(){}});
assert.ok(new URL(sample.location.href).searchParams.get('body').includes('Product document request'));
console.log('Contact checks passed: four request routes, prefill, edited values, field errors, special characters, long mailto fallback, copy parity and failure fallback. No email sent.');
